name = "VIvAAn chAUHAN"
preference = "I like dogs, dogs are very cute"

new_name = name.upper()
print(new_name)

new_name = name.lower()
print(new_name)

new_name = name.capitalize()
print(new_name)

new_prefernce = preference.replace("dogs", "cats")
print(new_prefernce)

length = len(new_prefernce)
print(length)